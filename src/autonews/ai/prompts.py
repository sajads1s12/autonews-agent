BANNED_PHRASES = (
    "جدير بالذكر", "الجدير بالذكر", "في خبر مفاجئ", "لا تفوّت", "باختصار شديد",
    "هل تعلم", "من نافلة القول", "وتجدر الإشارة", "في تطور مفاجئ ومثير",
    "كما هو معروف", "وعلى صعيد متصل", "في سياق متصل", "وفي هذا الإطار",
    "علمنا", "وفي التفاصيل", "وفي سياق منفصل", "أثار جدلاً واسعاً",
)


def build_user_prompt(article: Article, channel: Channel, variant: str = "A",
                      breaking: bool = False, *, context_hint: str = "",
                      is_update: bool = False, previous_title: str = "") -> str:
    """بناء طلب المستخدم الكامل (مع سياق المناسبات والتحديثات وA/B)."""

    max_body = min(420, max(180, int(channel.max_chars * 0.62)))
    emoji_rule = ("أضف ما بين 1 و3 إيموجي في مواضع دلالية فقط." if channel.add_emoji
                  else "لا تستخدم أي إيموجي.")
    hashtag_rule = (f"أضف {channel.add_hashtags} هاشتاغات قصيرة ذات صلة مباشرة."
                    if channel.add_hashtags > 0 else "لا تضف هاشتاغات.")

    style = channel.style or "أسلوب إخباري مباشر وموجز."
    if variant == "B" and channel.style_b:
        style = channel.style_b

    # قواعد خاصة بكل منصّة
    platform_rules = {
        "telegram": "منصّة قنوات: عنوان واضح + جسم مركّز. لا سؤال تفاعل في النهاية.",
        "facebook": "منصّة تفاعل: ابدأ بجملة تخطف، وأنهِ بسؤال واحد قصير يدفع للتعليق.",
        "x": "منصّة قصيرة: العنوان هو التغريدة (≤ 120 حرفاً)، ثم سطر شرح واحد. لا تكرّر العنوان في الجسم.",
    }.get(channel.platform, "")

    payload = {
        "platform": channel.platform,
        "channel_name": channel.name,
        "style_required": style,
        "variant": variant,
        "is_breaking": breaking,
        "is_update": is_update,
        "occasion_context": context_hint or None,
        "previous_headline": previous_title or None,
        "limits": {
            "body_max_chars": max_body,
            "post_max_chars": channel.max_chars,
            "hashtags": channel.add_hashtags,
            "emoji": channel.add_emoji,
        },
        "article": {
            "title": article.title,
            "source": article.source_name,
            "published": human_age(article.published),
            "summary": truncate(article.summary, 900),
            "extra_content": truncate(article.content, 1100),
            "tags": article.tags[:6],
        },
    }

    breaking_rules = ""
    if breaking:
        breaking_rules = (
            "\n- **خبر عاجل**: ابدأ بالنتيجة نفسها بلا أي مقدمة. صيغة الحاضر. "
            "لا تكتب «عاجل» في العنوان إن كان الخبر عادياً — العجلة تُقاس بالمعلومة لا بالكلمة."
        )
    update_rules = ""
    if is_update:
        update_rules = (
            f"\n- **تحديث على خبر سابق** (عنوانه: «{truncate(previous_title, 90)}»): "
            "ركّز على **ما الجديد فقط**، ولا تُعِد سرد ما سبق. اذكر التغيير صريحاً "
            "(تمديد/رفع/إلغاء/حصيلة جديدة) في أول جملة."
        )
    occasion_rules = ""
    if context_hint:
        occasion_rules = (
            f"\n- **سياق المناسبة اليوم**: {context_hint}. "
            "اجعل النبرة مناسبة للسياق، وركّز على ما يهمّ الناس فعلاً في هذه المناسبة "
            "(دوام، أسعار، خدمات، مواقيت، إجراءات) بدل الخطابة."
        )

    return f"""أعد صياغة الخبر التالي لمنصّة «{channel.platform}» وفق الإعدادات المرافقة.

{json.dumps(payload, ensure_ascii=False, indent=2)}

شروط الصياغة:
- **الخطّاف أولاً**: ابدأ العنوان والعنصر "hook" بأهم نتيجة أو رقم أو أثر على القارئ — لا بأسماء المسؤولين ولا بـ«أعلن/صرّح».
- العنوان: 7–12 كلمة، محدّد، بلا كلمات ميتة.
- النص (body): بحد أقصى 3 جمل قصيرة و{max_body} حرفاً. اكتب أهم معلومة ثم تفصيلاً ضرورياً فقط؛ لا تكرر العنوان ولا تطِل.
- {emoji_rule}
- {hashtag_rule}
- platform_rule: {platform_rules}
- صنّف في "category" من: (سياسة، اقتصاد، تقنية، رياضة، صحة، علوم، ثقافة، مجتمع، دولي، متنوّع).
- "key_points": أخرج مصفوفة فارغة []؛ لا تنشئ نقاطاً أو قائمة منفصلة.
- "sensitive": true فقط للعنف الصريح أو المحتوى الحسّاس.
- أي رقم تذكره يجب أن يكون موجوداً حرفياً في الخبر الأصلي.
- تجنّب هذه العبارات تماماً: {", ".join(BANNED_PHRASES[:8])} …{breaking_rules}{update_rules}{occasion_rules}

تذكير: أخرج JSON صحيحاً فقط.
"""


def build_repair_prompt(raw: str) -> str:
    """طلب إصلاح عندما يعيد النموذج JSON غير صالح."""
    return (
        "النص التالي كان يجب أن يكون JSON صالحاً لكنه غير صالح. "
        "أعد صياغته كـ JSON صالح بالمفاتيح المطلوبة فقط "
        "(title, body, hook, hashtags, category, key_points, sensitive, reader_value) "
        "دون أي شرح إضافي:\n\n" + truncate(raw, 3000)
    )


